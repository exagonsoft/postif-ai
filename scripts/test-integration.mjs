async function request(route, cookie, body, expected = 200) {
  const response = await fetch(origin + route, { method: body ? "POST" : "GET", headers: { ...(cookie ? { Cookie: cookie } : {}), ...(body ? { "Content-Type": "application/json" } : {}) }, body: body ? JSON.stringify(body) : undefined });
  const raw = await response.text();
  let data;
  try { data = JSON.parse(raw); } catch { throw new Error(`${route} returned HTTP ${response.status} instead of JSON. Inspect the dev server log.`); }
  assert.equal(response.status, expected, `${route}: ${JSON.stringify(data)}`);
  return { data, cookie: response.headers.get("set-cookie")?.split(";")[0], setCookie: response.headers.get("set-cookie") };
}
