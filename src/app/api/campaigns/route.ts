import { NextResponse } from "next/server";
import { db } from "@/db";
import { campaigns, posts, auditLogs } from "@/db/schema";
import { and, eq } from "drizzle-orm";
import { getAuthContext } from "@/lib/auth";

export async function POST(req: Request) {
  try {
    const ctx = await getAuthContext();
    if (!ctx || !ctx.workspace || !ctx.user || !ctx.activeBrand) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const body = await req.json();
    const action = body.action as string;

    if (action === "create") {
      const platforms = Array.isArray(body.platforms)
        ? body.platforms
        : ["linkedin", "x", "instagram"];

      const [created] = await db
        .insert(campaigns)
        .values({
          workspaceId: ctx.workspace.id,
          brandId: Number(body.brandId || ctx.activeBrand.id),
          name: String(body.name || "Untitled Campaign").trim(),
          description: String(body.description || "").trim(),
          objective: String(body.objective || "Brand Awareness & Lead Generation").trim(),
          audience: String(body.audience || ctx.activeBrand.targetAudience || "").trim(),
          platforms,
          status: String(body.status || "active"),
          startDate: String(body.startDate || new Date().toISOString().slice(0, 10)),
          endDate: String(
            body.endDate ||
              new Date(Date.now() + 28 * 24 * 3600 * 1000).toISOString().slice(0, 10)
          ),
          strategySummary: String(body.strategySummary || "").trim(),
          contentThemes: Array.isArray(body.contentThemes) ? body.contentThemes : [],
          weeklyCadence: Number(body.weeklyCadence || 4),
          isSampleData: false,
        })
        .returning();

      // If samplePosts were generated by the AI Campaign Architect, create draft posts linked to the campaign
      if (Array.isArray(body.samplePosts)) {
        for (const sp of body.samplePosts) {
          const sched = new Date(
            Date.now() + Math.max(1, Number(sp.dayOffset || 1)) * 24 * 3600 * 1000
          );
          const plat = String(sp.platform || platforms[0] || "linkedin");
          await db.insert(posts).values({
            workspaceId: ctx.workspace.id,
            brandId: created.brandId,
            campaignId: created.id,
            title: String(sp.title || "Campaign Post"),
            topic: created.name,
            baseContent: String(sp.content || ""),
            contentType: "Campaign Post",
            tone: ctx.activeBrand.tone,
            status: "draft",
            scheduledAt: sched,
            platforms: [plat],
            variants: {
              [plat]: {
                content: String(sp.content || ""),
                hashtags: ctx.activeBrand.suggestedHashtags.slice(0, 3),
                cta: "Learn more →",
                formatLabel: "Campaign Asset",
                characterCount: String(sp.content || "").length,
              },
            },
            createdByAgent: true,
          });
        }
      }

      await db.insert(auditLogs).values({
        workspaceId: ctx.workspace.id,
        actorEmail: ctx.user.email,
        action: "campaign.created",
        resourceType: "campaign",
        resourceId: String(created.id),
        metadata: { name: created.name },
      });

      return NextResponse.json({ ok: true, campaign: created });
    }

    if (action === "update_status") {
      const campaignId = Number(body.campaignId);
      const status = String(body.status || "active");
      const [updated] = await db
        .update(campaigns)
        .set({ status })
        .where(
          and(
            eq(campaigns.id, campaignId),
            eq(campaigns.workspaceId, ctx.workspace.id)
          )
        )
        .returning();

      return NextResponse.json({ ok: true, campaign: updated });
    }

    if (action === "delete") {
      const campaignId = Number(body.campaignId);
      await db
        .delete(campaigns)
        .where(
          and(
            eq(campaigns.id, campaignId),
            eq(campaigns.workspaceId, ctx.workspace.id)
          )
        );
      return NextResponse.json({ ok: true });
    }

    return NextResponse.json({ error: "Invalid campaign action" }, { status: 400 });
  } catch (err) {
    console.error("Campaigns API error:", err);
    return NextResponse.json({ error: "Campaign operation failed" }, { status: 500 });
  }
}
